-- 01_schema.sql
-- Core warehouse schema (Person A, task A1).
-- Star schema: dimensions (dim_user, dim_date, campaign, ad_creative)
--              facts      (touchpoint, conversion, refund, spend)
-- EER: campaign is specialized into paid_campaign and email_campaign.
-- Support: audit_log (filled by the audit trigger in A5).

BEGIN;

-- ------------------------------------------------------------------
-- Dimensions
-- ------------------------------------------------------------------

CREATE TABLE core.dim_user (
    user_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hashed_id    CHAR(64) NOT NULL UNIQUE,          -- SHA-256 hex of the raw user id
    signup_date  DATE     NOT NULL
);

CREATE TABLE core.dim_date (
    date_id      INTEGER  PRIMARY KEY,              -- yyyymmdd, e.g. 20261027
    full_date    DATE     NOT NULL UNIQUE,
    day_of_week  SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),   -- ISO: 1 = Monday
    month        SMALLINT NOT NULL CHECK (month BETWEEN 1 AND 12),
    year         SMALLINT NOT NULL,
    CONSTRAINT ck_dim_date_id CHECK (
        date_id = EXTRACT(YEAR  FROM full_date)::INT * 10000
                + EXTRACT(MONTH FROM full_date)::INT * 100
                + EXTRACT(DAY   FROM full_date)::INT
    )
);

-- Reference data: every day from 2024 to 2027 (extend if the generator needs more).
INSERT INTO core.dim_date (date_id, full_date, day_of_week, month, year)
SELECT to_char(d, 'YYYYMMDD')::INT,
       d::DATE,
       EXTRACT(ISODOW FROM d)::SMALLINT,
       EXTRACT(MONTH  FROM d)::SMALLINT,
       EXTRACT(YEAR   FROM d)::SMALLINT
FROM generate_series('2024-01-01'::DATE, '2027-12-31'::DATE, INTERVAL '1 day') AS g(d);

-- ------------------------------------------------------------------
-- Campaign (superclass) and its two subclasses (EER specialization)
-- ------------------------------------------------------------------
-- Disjoint: campaign_type is stored once, and each subclass table carries a
-- fixed campaign_type that must match the parent row through a composite FK,
-- so a campaign cannot appear in both subclass tables.
-- Total participation (every campaign must have a subclass row) is checked by
-- the ingestion procedure in A5.

CREATE TABLE core.campaign (
    campaign_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel        TEXT          NOT NULL CHECK (channel IN ('google', 'meta', 'tiktok', 'email')),
    campaign_type  TEXT          NOT NULL CHECK (campaign_type IN ('paid', 'email')),
    campaign_name  TEXT          NOT NULL,
    budget         NUMERIC(12,2) NOT NULL CHECK (budget >= 0),
    CONSTRAINT uq_campaign_name UNIQUE (channel, campaign_name),
    CONSTRAINT uq_campaign_type UNIQUE (campaign_id, campaign_type),
    -- email channel <=> email campaign; every other channel is paid
    CONSTRAINT ck_campaign_channel_type CHECK ((channel = 'email') = (campaign_type = 'email'))
);

CREATE TABLE core.paid_campaign (
    campaign_id    INTEGER       PRIMARY KEY,
    campaign_type  TEXT          NOT NULL DEFAULT 'paid' CHECK (campaign_type = 'paid'),
    bid_strategy   TEXT          NOT NULL CHECK (bid_strategy IN ('cpc', 'cpm', 'target_roas', 'manual')),
    daily_budget   NUMERIC(10,2) NOT NULL CHECK (daily_budget >= 0),
    FOREIGN KEY (campaign_id, campaign_type)
        REFERENCES core.campaign (campaign_id, campaign_type) ON DELETE CASCADE
);

CREATE TABLE core.email_campaign (
    campaign_id    INTEGER PRIMARY KEY,
    campaign_type  TEXT    NOT NULL DEFAULT 'email' CHECK (campaign_type = 'email'),
    list_size      INTEGER NOT NULL CHECK (list_size >= 0),
    send_time      TIME    NOT NULL,
    FOREIGN KEY (campaign_id, campaign_type)
        REFERENCES core.campaign (campaign_id, campaign_type) ON DELETE CASCADE
);

CREATE TABLE core.ad_creative (
    creative_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id    INTEGER NOT NULL REFERENCES core.campaign (campaign_id),
    creative_name  TEXT    NOT NULL,
    creative_type  TEXT    NOT NULL CHECK (creative_type IN ('image', 'video', 'carousel', 'text', 'email_template')),
    description    TEXT,                             -- source text for the creative embeddings (B5)
    -- lets touchpoint prove that its creative belongs to its campaign
    CONSTRAINT uq_creative_campaign UNIQUE (creative_id, campaign_id)
);

-- ------------------------------------------------------------------
-- Facts
-- ------------------------------------------------------------------

CREATE TABLE core.touchpoint (
    touchpoint_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES core.dim_user (user_id),
    campaign_id    INTEGER     NOT NULL,
    creative_id    INTEGER     NOT NULL,
    touchpoint_ts  TIMESTAMPTZ NOT NULL,
    event_type     TEXT        NOT NULL CHECK (event_type IN ('impression', 'click')),
    -- UTC calendar day of touchpoint_ts, computed by the database so it can never disagree with it
    date_id        INTEGER GENERATED ALWAYS AS (
                       EXTRACT(YEAR  FROM touchpoint_ts AT TIME ZONE 'UTC')::INT * 10000
                     + EXTRACT(MONTH FROM touchpoint_ts AT TIME ZONE 'UTC')::INT * 100
                     + EXTRACT(DAY   FROM touchpoint_ts AT TIME ZONE 'UTC')::INT
                   ) STORED NOT NULL REFERENCES core.dim_date (date_id),
    -- blocks duplicate event ingestion
    CONSTRAINT uq_touchpoint_event UNIQUE (user_id, touchpoint_ts, event_type),
    -- the creative must belong to the campaign (also enforces Campaign 1-M Touchpoint)
    CONSTRAINT fk_touchpoint_creative FOREIGN KEY (creative_id, campaign_id)
        REFERENCES core.ad_creative (creative_id, campaign_id)
);

CREATE TABLE core.conversion (
    conversion_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT        NOT NULL REFERENCES core.dim_user (user_id),
    order_id         TEXT          NOT NULL UNIQUE,   -- also blocks duplicate purchase ingestion
    conversion_ts    TIMESTAMPTZ   NOT NULL,
    revenue          NUMERIC(12,2) NOT NULL CHECK (revenue > 0),
    currency         CHAR(3)       NOT NULL DEFAULT 'USD',
    refunded_amount  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (refunded_amount >= 0),  -- kept up to date by the refund trigger (A5)
    net_revenue      NUMERIC(12,2) GENERATED ALWAYS AS (revenue - refunded_amount) STORED,
    date_id          INTEGER GENERATED ALWAYS AS (
                         EXTRACT(YEAR  FROM conversion_ts AT TIME ZONE 'UTC')::INT * 10000
                       + EXTRACT(MONTH FROM conversion_ts AT TIME ZONE 'UTC')::INT * 100
                       + EXTRACT(DAY   FROM conversion_ts AT TIME ZONE 'UTC')::INT
                     ) STORED NOT NULL REFERENCES core.dim_date (date_id),
    CONSTRAINT ck_conversion_refund_limit CHECK (refunded_amount <= revenue)
);

CREATE TABLE core.refund (
    refund_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversion_id  BIGINT        NOT NULL REFERENCES core.conversion (conversion_id),
    refund_amount  NUMERIC(12,2) NOT NULL CHECK (refund_amount > 0),
    refund_date    DATE          NOT NULL
);

CREATE TABLE core.spend (
    campaign_id  INTEGER       NOT NULL REFERENCES core.campaign (campaign_id),
    date_id      INTEGER       NOT NULL REFERENCES core.dim_date (date_id),
    spend        NUMERIC(12,2) NOT NULL CHECK (spend >= 0),
    PRIMARY KEY (campaign_id, date_id)
);

-- ------------------------------------------------------------------
-- Support
-- ------------------------------------------------------------------

CREATE TABLE core.audit_log (
    audit_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name  TEXT        NOT NULL,
    operation   TEXT        NOT NULL CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
    row_pk      TEXT,
    old_data    JSONB,
    new_data    JSONB,
    changed_by  TEXT        NOT NULL DEFAULT current_user,
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMIT;
